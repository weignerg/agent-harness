    def test_tool_runner_no_deprecation_warning(self):
        """Verify inspect.iscoroutinefunction is used and zero DeprecationWarning is emitted."""
        with warnings.catch_warnings(record=True) as caught_warnings:
            warnings.simplefilter("always")

            registry = DynamicToolRegistry()
            registry.register_core_tool("sync_echo", lambda msg: f"sync:{msg}")

            async def async_echo(msg: str) -> str:
                return f"async:{msg}"

            registry.register_core_tool("async_echo", async_echo)

            r1 = asyncio.run(registry.call_tool_async("sync_echo", {"msg": "hello"}))
            self.assertEqual(r1, "sync:hello")

            r2 = asyncio.run(registry.call_tool_async("async_echo", {"msg": "world"}))
            self.assertEqual(r2, "async:world")

            dep_warnings = [w for w in caught_warnings if issubclass(w.category, DeprecationWarning)]
            self.assertEqual(
                len(dep_warnings),
                0,
                f"Unexpected DeprecationWarning emitted: {[str(w.message) for w in dep_warnings]}",
            )

