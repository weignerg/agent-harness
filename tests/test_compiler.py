def parse_yaml_frontmatter(text: str) -> Dict[str, Any]:
    """Simple parser for the frontmatter subset generated by compiler.py."""
    if not text.startswith("---"):
        return {}
    parts = text.split("---", 2)
    if len(parts) < 3:
        return {}
    fm_lines = parts[1].strip().splitlines()
    data: Dict[str, Any] = {}
    current_section: Dict[str, Any] | None = None
    section_name: str | None = None
    sub_section: Dict[str, Any] | None = None
    sub_section_name: str | None = None

    for line in fm_lines:
        line_stripped = line.strip()
        if not line_stripped:
            continue
        indent = len(line) - len(line.lstrip())

        if indent == 0:
            current_section = None
            section_name = None
            sub_section = None
            sub_section_name = None
            if ":" in line_stripped:
                k, v = line_stripped.split(":", 1)
                k, v = k.strip().strip('"\''), v.strip().strip('"\'')
                if v:
                    data[k] = v
                else:
                    data[k] = {}
                    current_section = data[k]
                    section_name = k
        elif indent == 2 and current_section is not None:
            sub_section = None
            sub_section_name = None
            if ":" in line_stripped:
                k, v = line_stripped.split(":", 1)
                k, v = k.strip().strip('"\''), v.strip().strip('"\'')
                if v:
                    current_section[k] = v
                else:
                    current_section[k] = {}
                    sub_section = current_section[k]
                    sub_section_name = k
        elif indent == 4 and sub_section is not None:
            if ":" in line_stripped:
                k, v = line_stripped.split(":", 1)
                k, v = k.strip().strip('"\''), v.strip().strip('"\'')
                sub_section[k] = v

    return data


class TestCompilerAndPermissionGates(unittest.TestCase):
    def setUp(self):
        self.manifest_path = CORE_DIR / "manifest.json"
        self.assertTrue(self.manifest_path.is_file(), "core/manifest.json not found")
        self.manifest = json.loads(self.manifest_path.read_text(encoding="utf-8"))
        self.roles = self.manifest.get("roles", {})
        self.tier_models = self.manifest.get("model_tiers", {})

    def test_manifest_roles_have_allowed_subagents(self):
        """Verify each role in core/manifest.json defines expected allowed_subagents."""
        expected = {
            "supreme-orchestrator": ["team-orchestrator"],
            "team-orchestrator": ["architect", "worker", "tester", "reviewer", "scout", "grunt"],
            "architect": ["scout"],
            "reviewer": ["scout"],
            "worker": ["grunt", "scout"],
            "tester": ["grunt", "scout"],
            "scout": [],
            "grunt": [],
        }
        for role, expected_allowed in expected.items():
            self.assertIn(role, self.roles, f"Missing role: {role}")
            actual = self.roles[role].get("allowed_subagents")
            self.assertEqual(
                actual,
                expected_allowed,
                f"Role {role} allowed_subagents mismatch: {actual} != {expected_allowed}",
            )

    def test_compile_opencode_frontmatter_task_fanout(self):
        """Verify per-role task permission fan-out maps generated by _build_opencode_frontmatter."""
        # 1. supreme-orchestrator: only team-orchestrator
        supreme_fm = parse_yaml_frontmatter(_build_opencode_frontmatter("supreme-orchestrator", self.roles["supreme-orchestrator"], self.tier_models))
        supreme_task = supreme_fm.get("permission", {}).get("task")
        self.assertIsInstance(supreme_task, dict)
        self.assertEqual(supreme_task.get("*"), "deny")
        self.assertEqual(supreme_task.get("team-orchestrator"), "allow")
        self.assertNotIn("architect", supreme_task)

        # 2. team-orchestrator: leaf and workhorse roles
        team_fm = parse_yaml_frontmatter(_build_opencode_frontmatter("team-orchestrator", self.roles["team-orchestrator"], self.tier_models))
        team_task = team_fm.get("permission", {}).get("task")
        self.assertIsInstance(team_task, dict)
        self.assertEqual(team_task.get("*"), "deny")
        for sub in ("architect", "worker", "tester", "reviewer", "scout", "grunt"):
            self.assertEqual(team_task.get(sub), "allow")
        self.assertNotIn("supreme-orchestrator", team_task)

        # 3. architect: scout only
        arch_fm = parse_yaml_frontmatter(_build_opencode_frontmatter("architect", self.roles["architect"], self.tier_models))
        arch_task = arch_fm.get("permission", {}).get("task")
        self.assertIsInstance(arch_task, dict)
        self.assertEqual(arch_task.get("*"), "deny")
        self.assertEqual(arch_task.get("scout"), "allow")
        self.assertNotIn("worker", arch_task)

        # 4. reviewer: scout only
        rev_fm = parse_yaml_frontmatter(_build_opencode_frontmatter("reviewer", self.roles["reviewer"], self.tier_models))
        rev_task = rev_fm.get("permission", {}).get("task")
        self.assertIsInstance(rev_task, dict)
        self.assertEqual(rev_task.get("*"), "deny")
        self.assertEqual(rev_task.get("scout"), "allow")

        # 5. worker & tester: grunt and scout
        for role_name in ("worker", "tester"):
            w_fm = parse_yaml_frontmatter(_build_opencode_frontmatter(role_name, self.roles[role_name], self.tier_models))
            w_task = w_fm.get("permission", {}).get("task")
            self.assertIsInstance(w_task, dict)
            self.assertEqual(w_task.get("*"), "deny")
            self.assertEqual(w_task.get("grunt"), "allow")
            self.assertEqual(w_task.get("scout"), "allow")
            self.assertNotIn("reviewer", w_task)

        # 6. scout & grunt: deny (string literal)
        for role_name in ("scout", "grunt"):
            leaf_fm = parse_yaml_frontmatter(_build_opencode_frontmatter(role_name, self.roles[role_name], self.tier_models))
            leaf_task = leaf_fm.get("permission", {}).get("task")
            self.assertEqual(leaf_task, "deny", f"Role {role_name} task permission should be 'deny'")

    def test_compile_opencode_frontmatter_bash_rules(self):
        """Verify process-killing deny, outward-facing ask, and read-only role restrictions."""
        process_kills = [
            "kill *",
            "pkill *",
            "killall *",
            "systemctl stop *",
            "systemctl --user stop *",
            "claude stop *",
            "claude kill *",
        ]
        outward_mutations = [
            "git push*",
            "git merge*",
            "gh pr create*",
            "gh pr merge*",
            "gh pr review*",
            "gh pr comment*",
            "gh issue create*",
            "gh issue close*",
            "gh issue comment*",
            "gh workflow run*",
        ]
        mutating_git = [
            "git commit*",
            "git merge*",
            "git rebase*",
            "git reset*",
            "git checkout*",
        ]

        # Check worker has process-killing deny and outward-facing ask, but NOT mutating git commit deny
        worker_fm = parse_yaml_frontmatter(_build_opencode_frontmatter("worker", self.roles["worker"], self.tier_models))
        w_bash = worker_fm.get("permission", {}).get("bash", {})
        for cmd in process_kills:
            self.assertEqual(w_bash.get(cmd), "deny", f"Worker missing deny on {cmd}")
        for cmd in outward_mutations:
            self.assertEqual(w_bash.get(cmd), "ask", f"Worker missing ask on {cmd}")
        self.assertNotIn("git commit*", w_bash, "Worker should not have git commit* denied")

        # Check supreme-orchestrator and read-only roles have all mutating git commands denied
        for ro_role in ("supreme-orchestrator", "architect", "reviewer", "scout"):
            ro_fm = parse_yaml_frontmatter(_build_opencode_frontmatter(ro_role, self.roles[ro_role], self.tier_models))
            ro_bash = ro_fm.get("permission", {}).get("bash", {})
            for cmd in process_kills:
                self.assertEqual(ro_bash.get(cmd), "deny", f"{ro_role} missing deny on {cmd}")
            for cmd in outward_mutations:
                # If command is denied by role override (e.g. git merge*), role deny takes precedence
                if cmd in mutating_git:
                    self.assertEqual(ro_bash.get(cmd), "deny", f"{ro_role} must have {cmd} denied")
                else:
                    self.assertEqual(ro_bash.get(cmd), "ask", f"{ro_role} missing ask on {cmd}")
            for cmd in mutating_git:
                self.assertEqual(ro_bash.get(cmd), "deny", f"{ro_role} must have {cmd} denied")

        # Check team-orchestrator has git commit* and git merge* denied
        team_fm = parse_yaml_frontmatter(_build_opencode_frontmatter("team-orchestrator", self.roles["team-orchestrator"], self.tier_models))
        team_bash = team_fm.get("permission", {}).get("bash", {})
        self.assertEqual(team_bash.get("git commit*"), "deny")
        self.assertEqual(team_bash.get("git merge*"), "deny")

    def test_opencode_json_permissions(self):
        """Verify config/opencode/opencode.json contains required bash deny/ask rules."""
        cfg_path = CONFIG_DIR / "opencode" / "opencode.json"
        self.assertTrue(cfg_path.is_file(), "config/opencode/opencode.json not found")
        data = json.loads(cfg_path.read_text(encoding="utf-8"))

        perm_bash = data.get("permission", {}).get("bash", {})
        self.assertIsInstance(perm_bash, dict)

        # Process-killing deny gates
        for cmd in ("kill *", "pkill *", "killall *", "systemctl stop *", "systemctl --user stop *", "claude stop *", "claude kill *"):
            self.assertEqual(perm_bash.get(cmd), "deny", f"opencode.json bash missing deny for {cmd}")

        # Outward-facing mutating ask gates
        for cmd in ("git push*", "git merge*", "gh pr create*", "gh pr merge*", "gh pr review*", "gh pr comment*", "gh issue create*", "gh issue close*", "gh issue comment*", "gh workflow run*"):
            self.assertEqual(perm_bash.get(cmd), "ask", f"opencode.json bash missing ask for {cmd}")

        # Agent restrictions
        agents = data.get("agent", {})
        # supreme-orchestrator, architect, reviewer, scout
        for ro_agent in ("supreme-orchestrator", "architect", "reviewer", "scout"):
            self.assertIn(ro_agent, agents)
            agent_bash = agents[ro_agent].get("permission", {}).get("bash", {})
            for cmd in ("git commit*", "git merge*", "git rebase*", "git reset*", "git checkout*"):
                self.assertEqual(agent_bash.get(cmd), "deny", f"{ro_agent} in opencode.json missing deny on {cmd}")

        # team-orchestrator
        self.assertIn("team-orchestrator", agents)
        to_bash = agents["team-orchestrator"].get("permission", {}).get("bash", {})
        self.assertEqual(to_bash.get("git commit*"), "deny")
        self.assertEqual(to_bash.get("git merge*"), "deny")

